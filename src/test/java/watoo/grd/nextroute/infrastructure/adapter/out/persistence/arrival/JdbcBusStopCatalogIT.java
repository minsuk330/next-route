package watoo.grd.nextroute.infrastructure.adapter.out.persistence.arrival;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Connection;
import javax.sql.DataSource;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.FileSystemResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.datasource.init.ScriptUtils;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.utility.DockerImageName;

/**
 * #577 카탈로그 조회가 어느 공급자를 부를지 정하는 SQL 계약. {@code regional_bus_route_stop} 은 실제 마이그레이션(V56, V64)을
 * 돌린다. {@code bus_stop} 은 V1 baseline 이 PostGIS 를 요구해 조회가 쓰는 칸만 V1 그대로 옮겼다.
 */
@DisplayName("정류장 단위 도착 카탈로그 SQL(#577)")
class JdbcBusStopCatalogIT {

    static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>(DockerImageName.parse("postgres:17"));
    static JdbcTemplate jdbc;
    static JdbcBusStopCatalog catalog;

    @BeforeAll
    static void setUp() throws Exception {
        POSTGRES.start();
        DataSource ds = new DriverManagerDataSource(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
        try (Connection c = ds.getConnection()) {
            ScriptUtils.executeSqlScript(c, new FileSystemResource(
                    "src/main/resources/db/migration/V56__create_regional_bus_route_stop.sql"));
            ScriptUtils.executeSqlScript(c, new FileSystemResource(
                    "src/main/resources/db/migration/V64__regional_bus_route_stop_stop_no.sql"));
        }
        jdbc = new JdbcTemplate(ds);
        jdbc.execute("CREATE TABLE bus_stop (id bigint generated by default as identity primary key,"
                + " deleted_at timestamp(6), ars_id varchar(255), stop_id varchar(255) not null unique,"
                + " stop_name varchar(255))");
        jdbc.update("INSERT INTO bus_stop (stop_id, ars_id) VALUES"
                + " ('121000009', '22009'), ('121000091', ' 22167 '), ('100000001', '0'), ('100000002', ''),"
                + " ('100000003', NULL)");
        jdbc.update("INSERT INTO bus_stop (stop_id, ars_id, deleted_at) VALUES ('100000004', '11111', now())");
        jdbc.update("INSERT INTO regional_bus_route_stop (provider, route_id, city_code, stop_id, seq, waypoint, loaded_at)"
                + " VALUES ('GG', '200000296', '31010', '121000009', 1, false, now()),"
                + " ('GG', '200000297', NULL, '201000107', 1, NULL, now()),"
                + " ('GG', '200000298', NULL, '209000001', 1, true, now()),"
                + " ('TAGO', 'MPB1', '36420', 'MPB100100003', 1, NULL, now()),"
                + " ('TAGO', 'MPB2', '36010', 'MPB100100003', 1, NULL, now()),"
                + " ('TAGO', 'MPB3', '36010', 'MPB100100003', 2, NULL, now()),"
                + " ('TAGO', 'MPB4', NULL, 'MPB100100009', 1, NULL, now())");
        catalog = new JdbcBusStopCatalog(jdbc);
    }

    @Test
    @DisplayName("서울 번호: 살아 있고 비지 않은 번호만, 앞뒤 공백 제거")
    void seoulArsId() {
        assertThat(catalog.seoulArsId("121000009")).contains("22009");
        assertThat(catalog.seoulArsId("121000091")).contains("22167");
        assertThat(catalog.seoulArsId("100000001")).as("가상 정류장 0").isEmpty();
        assertThat(catalog.seoulArsId("100000002")).isEmpty();
        assertThat(catalog.seoulArsId("100000003")).isEmpty();
        assertThat(catalog.seoulArsId("100000004")).as("지워진 정류장").isEmpty();
        assertThat(catalog.seoulArsId("199999999")).isEmpty();
    }

    @Test
    @DisplayName("경기 정류장: 경유 가상점만 있는 id 는 아니다, waypoint null 은 탈 수 있는 정류장")
    void gyeonggiStop() {
        assertThat(catalog.isGyeonggiStop("121000009")).isTrue();
        assertThat(catalog.isGyeonggiStop("201000107")).isTrue();
        assertThat(catalog.isGyeonggiStop("209000001")).isFalse();
        assertThat(catalog.isGyeonggiStop("MPB100100003")).as("TAGO 줄은 경기가 아니다").isFalse();
    }

    @Test
    @DisplayName("TAGO 도시코드: 중복 없이 정렬, null 은 뺀다")
    void tagoCityCodes() {
        assertThat(catalog.tagoCityCodes("MPB100100003")).containsExactly("36010", "36420");
        assertThat(catalog.tagoCityCodes("MPB100100009")).isEmpty();
        assertThat(catalog.tagoCityCodes("121000009")).as("경기 줄의 city_code 는 TAGO 가 아니다").isEmpty();
    }
}
