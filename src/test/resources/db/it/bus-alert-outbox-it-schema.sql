-- IT 전용 스키마. bus outbox(enqueue/relay/claim) 검증용.
-- 복제 원본: V19(bus_arrival_alert, bus-alert-it-schema.sql 와 동일) + V28(bus_alert_notification).
-- 마이그레이션 추가 시 이 파일 갱신(drift 시 IT 가 깨져 알려줌).

CREATE TABLE users (
    id            bigint generated by default as identity primary key,
    created_at    timestamp(6),
    updated_at    timestamp(6),
    deleted_at    timestamp(6),
    toss_user_key bigint,
    -- V34. 토큰 세대 번호. 엔티티가 매핑하므로 없으면 users 조회 SQL 이 깨진다.
    token_generation integer not null default 0
);

CREATE TABLE bus_arrival_alert (
    id                    bigint generated by default as identity primary key,
    created_at            timestamp(6),
    updated_at            timestamp(6),
    deleted_at            timestamp(6),
    user_id               bigint        not null references users,
    stop_id               varchar(255)  not null,
    route_id              varchar(255)  not null,
    ord                   integer       not null,
    route_name            varchar(255)  not null,
    stop_name             varchar(255)  not null,
    user_eta              timestamp(6)  not null,
    bus_arrival_minutes   integer       not null,
    status                varchar(255)  not null
        constraint bus_arrival_alert_status_check
            check (status in ('PENDING', 'PROCESSING', 'SENT', 'FAILED', 'EXPIRED', 'CANCELED')),
    expires_at            timestamp(6)  not null,
    sent_at               timestamp(6),
    processing_started_at timestamp(6),
    last_attempt_at       timestamp(6),
    attempt_count         integer       not null default 0,
    last_failure_reason   varchar(500)
);

CREATE UNIQUE INDEX uq_bus_alert_active
    ON bus_arrival_alert (user_id, stop_id, route_id, ord)
    WHERE deleted_at IS NULL AND status IN ('PENDING', 'PROCESSING');

CREATE TABLE bus_alert_notification (
    id                    bigint generated by default as identity primary key,
    created_at            timestamp(6),
    updated_at            timestamp(6),
    deleted_at            timestamp(6),
    alert_id              bigint       not null references bus_arrival_alert,
    dedup_key             varchar(255) not null,
    channel               varchar(50)  not null,
    event_type            varchar(50)  not null,
    status                varchar(255) not null
        constraint bus_alert_notification_status_check
            check (status in ('PENDING', 'PROCESSING', 'SENT', 'FAILED', 'DEAD', 'CANCELED')),
    scheduled_at          timestamp(6) not null,
    payload               varchar(1000),
    attempt_count         integer      not null default 0,
    requeue_count         integer      not null default 0,
    last_requeued_at      timestamp(6),
    processing_started_at timestamp(6),
    sent_at               timestamp(6),
    last_failure_reason   varchar(500)
);

CREATE UNIQUE INDEX uq_bus_alert_notification_dedup ON bus_alert_notification (dedup_key);
CREATE INDEX idx_bus_alert_notification_status_scheduled
    ON bus_alert_notification (status, scheduled_at) WHERE deleted_at IS NULL;
