-- IT 전용 스키마. 지도 스냅샷 쿼리(필터/정렬/버전 프로브) 검증용.
-- 복제 원본: V1__baseline.sql 의 bus_stop. 마이그레이션 변경 시 이 파일 갱신.
--
-- geom(geography(Point,4326)) 컬럼은 뺐다: postgis 없는 postgres:17 을 쓰고,
-- 스냅샷 쿼리는 geom 을 보지 않는다(좌표 컬럼으로 판단하는 것이 계약). geom 을 보는
-- findNearby 를 이 IT 에 추가하려면 postgis 이미지로 바꿔야 한다.

CREATE TABLE bus_stop (
    id         bigint generated by default as identity primary key,
    created_at timestamp(6),
    deleted_at timestamp(6),
    updated_at timestamp(6),
    ars_id     varchar(255),
    latitude   double precision,
    longitude  double precision,
    stop_id    varchar(255) not null unique,
    stop_name  varchar(255)
);
