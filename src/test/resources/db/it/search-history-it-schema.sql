-- IT 전용 스키마. 검색 이력 upsert/trim(dedup collapse + cap) 검증용.
-- 복제 원본: V29(route_search_history) + users(FK 대상). 마이그레이션 변경 시 이 파일 갱신.

CREATE TABLE users (
    id            bigint generated by default as identity primary key,
    created_at    timestamp(6),
    updated_at    timestamp(6),
    deleted_at    timestamp(6),
    toss_user_key bigint
);

CREATE TABLE route_search_history (
    id           bigint generated by default as identity primary key,
    created_at   timestamp(6),
    updated_at   timestamp(6),
    deleted_at   timestamp(6),
    user_id      bigint           not null,
    startx       double precision not null,
    starty       double precision not null,
    endx         double precision not null,
    endy         double precision not null,
    start_name   varchar(255),
    end_name     varchar(255),
    path_count   integer,
    search_type  integer,
    searched_at  timestamp(6)     not null,
    constraint uk_search_history_user_coords unique (user_id, startx, starty, endx, endy),
    constraint fk_search_history_user foreign key (user_id) references users (id) on delete cascade
);

CREATE INDEX idx_search_history_user_time
    ON route_search_history (user_id, searched_at desc, id desc);
