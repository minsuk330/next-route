-- IT 전용 스키마. user_push_token(V39)의 FK 대상인 users 만 만든다.
--
-- user_push_token 자체는 여기에 복제하지 않는다. 테스트가 실제 V39 파일을 그대로 실행하므로
-- 마이그레이션과 검증 대상이 갈라질 여지가 없다(UserPushTokenSchemaIT 의 @Sql 참고).
--
-- 복제 원본: V1(users) + V16(toss_user_key) + V34(token_generation).
-- token_generation 이 빠지면 UserRepository 의 모든 쿼리가 깨진다.

CREATE TABLE users (
    id               bigint generated by default as identity primary key,
    created_at       timestamp(6),
    updated_at       timestamp(6),
    deleted_at       timestamp(6),
    toss_user_key    bigint,
    token_generation integer not null default 0
);
