package watoo.grd.nextroute.common.lock;

/**
 * 여러 인스턴스 중 한 대만 해야 하는 일의 리더 자격.
 *
 * <p>공급자를 부르는 수집기·감시자가 두 대에서 돌면 호출 한도를 두 배로 태우고, 변화 감지가 서로 다른
 * 스냅숏으로 번갈아 깜빡인다. 그래서 그 일은 리더만 한다. 리더가 죽으면 다른 인스턴스가 잠금 만료 뒤
 * 이어받는다.
 */
public interface LeaderLease {

    /**
     * 지금 리더인지. 마지막 갱신 성공 뒤 로컬 마감(만료 − 여유) 안에서만 참이다 — Redis 를 묻지 않는다.
     *
     * <p>부작용(캐시 삭제·트리거·공급자 호출) <b>직전</b>에 다시 물어야 한다. 긴 GC 정지로 마감이 지났는데
     * 모르고 쓰면, 그사이 새 리더와 둘이 같은 일을 한다.
     */
    boolean isLeader();

    /** 리더 자격이 바뀐 횟수(얻거나 잃음). 감지 기준선을 비울지 판단하는 데 쓴다. */
    long epoch();
}
