-- 악화 알림 피로 정책(#428 PR-1b). 경로 버전마다 "울릴 권리"를 여정 행에 한 번만 따낸다.
--
-- alert_claim_revision: 권리를 따낸 경로 버전. 재탐색 수락으로 경로 버전이 바뀌면 값이 달라져 새 권리가 자연히 열린다.
-- alert_claim_key: 권리를 가진 알림의 논리 키(채널을 뺀 키). 더 나쁜 알림이 아직 안 나간 그 알림을 대체하면 키를
--   대체한 쪽으로 옮기고(물려받기), 그 알림이 만료·실패로 실제로 안 나가면 둘 다 비운다(돌려받기).
--
-- 알림 행 개수를 세지 않고 여정 행 한 칸을 쓰는 이유: 위험 알림(평가기)·재탐색 알림·보드 push 가 서로 다른 트랜잭션과
-- 인스턴스에서 동시에 돈다. 세는 방식은 둘 다 "0건 → 울림"을 본다. 한 행 UPDATE 는 DB 가 하나만 이기게 해 준다.
--
-- 두 칸 모두 엔티티에 매핑하지 않는다(SQL 전용). JourneySession 을 통째로 저장하는 경로가 옛 값을 되써 권리를
-- 되살리거나 지우지 않게 하려는 것이다(V67 평가 선점 칸과 같은 선례).
ALTER TABLE journey_session
    ADD COLUMN alert_claim_revision integer NULL,
    ADD COLUMN alert_claim_key varchar(255) NULL;
