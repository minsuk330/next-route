-- 로그아웃이 이미 발급된 JWT 를 무효화할 수 있게 한다.
--
-- JWT 는 상태가 없다. 한 번 서명해서 내보내면 만료 전까지 서버가 개입할 수 없다.
-- 그래서 사용자마다 번호를 하나 두고 토큰에 함께 담는다. 로그아웃하면 번호를 올리고,
-- 요청이 올 때 토큰 속 번호와 이 값이 다르면 거부한다.
--
-- 기존 행은 전부 0 으로 시작한다. 이미 발급된 토큰에는 이 번호가 없는데,
-- 없으면 0 으로 해석하기로 했으므로(JwtProvider) 배포 순간 강제 로그아웃이 일어나지 않는다.
ALTER TABLE users
    ADD COLUMN token_generation integer NOT NULL DEFAULT 0;
