-- 탑승 열차 판정의 관측과 판단을 한 줄씩 쌓는다.
--
-- 왜 journey_telemetry_event 를 쓰지 않나. 그 표는 스스로를 "앱 이용행태 계측 원본이며 여정 상태
-- 전이의 근거로 쓰지 않는다"고 선언한다. 여기 쌓이는 것은 정확히 상태 전이의 근거다. 게다가
-- 그 표의 멱등 키(telemetry_id)는 앱이 만드는 값이라 서버 판단을 끼워 넣을 자리가 없다.
--
-- 이 표가 하는 일은 둘이다.
--   ① 왜 그 열차를 골랐는지 남긴다. 판정이 틀렸을 때 관문 값을 조정하려면 근거가 있어야 한다
--   ② 후보 목록의 원본이다. 잠정 판정의 후보들이 여기 남아야, 캐시가 날아간 뒤에도
--      "그 후보가 아니라 이 후보였다"는 교정이 가능하다

CREATE TABLE subway_binding_event (
    id                  bigint generated by default as identity primary key,
    created_at          timestamp(6) not null,
    updated_at          timestamp(6) not null,
    deleted_at          timestamp(6),

    -- 없는 단계를 가리키는 감사행이 생기지 않게 한다.
    journey_leg_id      bigint       not null references journey_leg(id),
    journey_id          bigint       not null references journey_session(id),
    route_revision      integer      not null
        constraint subway_binding_event_revision_check check (route_revision >= 1),
    leg_index           integer      not null
        constraint subway_binding_event_leg_index_check check (leg_index >= 0),

    -- EVIDENCE = 앱이 보낸 관측, DECISION = 서버가 내린 판단
    kind                varchar(10)  not null
        constraint subway_binding_event_kind_check check (kind in ('EVIDENCE', 'DECISION')),
    event_type          varchar(30)  not null
        constraint subway_binding_event_type_check check (event_type in (
            'MOVEMENT_START', 'STATION_STOP_EPISODE',
            'PENDING', 'PROVISIONAL', 'CONFIRMED', 'CORRECTED', 'ABANDONED',
            'USER_RESET', 'USER_NOT_BOARDED', 'INHERITED_ON_REROUTE')),

    -- 종류와 이름이 서로 맞아야 한다. 값 목록만 막으면 판단 행에 관측 이름이 들어간다.
    constraint subway_binding_event_kind_type_check check (
        (kind = 'EVIDENCE' and event_type in ('MOVEMENT_START', 'STATION_STOP_EPISODE'))
     or (kind = 'DECISION' and event_type not in ('MOVEMENT_START', 'STATION_STOP_EPISODE'))),

    -- 앱이 붙이는 순번. 같은 관측을 다시 보내도 한 번만 쌓이게 하는 근거다.
    evidence_sequence   integer
        constraint subway_binding_event_seq_check
            check (evidence_sequence is null or evidence_sequence >= 0),
    constraint subway_binding_event_evidence_seq_required check (
        kind <> 'EVIDENCE' or evidence_sequence is not null),

    -- 판정 규칙을 바꾼 뒤 과거 판단과 섞이지 않게 한다.
    algorithm_version   varchar(20),
    binding_version     integer,
    -- 어느 보정 세대에서 나온 판단인가. 후보 복구가 세대를 건너뛰면 사용자가 거부한 열차가
    -- 되살아난다.
    reset_generation    integer      not null default 0,

    -- 기기·원천이 말한 시각. 믿지 않는다 - 순서와 보관의 기준은 received_at 이다.
    occurred_at         timestamptz  not null,
    received_at         timestamptz  not null,

    -- 고른 열차 전체. 번호 하나만 남기면 나중에 그 열차를 다시 찾을 수 없다.
    chosen_train_no     varchar(32),
    chosen_service_date date,
    chosen_line_id      varchar(16),
    chosen_direction    varchar(10),
    constraint subway_binding_event_chosen_identity_check check (
        (chosen_train_no is null and chosen_service_date is null
         and chosen_line_id is null and chosen_direction is null)
     or (chosen_train_no is not null and chosen_service_date is not null
         and chosen_line_id is not null and chosen_direction is not null)),

    -- 후보 목록과 판단 근거. 칼럼으로 박지 않는 이유는 어떤 값이 쓸모 있는지 아직 모르기 때문이다.
    -- 관문을 한 번 조정할 때마다 필드가 바뀌는데 그때마다 마이그레이션을 만들 수는 없다.
    --   { motionInterval, departureInterval, e1, e2, clockSkew, localHeadway, gate,
    --     candidates: [{ trainNo, serviceDate, lineId, direction,
    --                    departureInterval, error, expectedNextArrivalAt, rejectReason }] }
    detail              jsonb,

    -- 같은 관측을 다시 보내면 조용히 무시한다. 종류를 포함하는 이유는 이동 시작과 정차가
    -- 각각 1 부터 세기 때문이다 - 빼면 서로의 1 번이 충돌한다.
    constraint uk_subway_binding_event_evidence
        unique (journey_leg_id, kind, event_type, evidence_sequence)
);

CREATE INDEX ix_subway_binding_event_journey
    ON subway_binding_event (journey_id, occurred_at);
-- 후보 복구가 이 인덱스로 돈다. 그 단계의 최근 판단부터 거슬러 읽는다.
CREATE INDEX ix_subway_binding_event_leg
    ON subway_binding_event (journey_leg_id, id DESC);
-- 보관 삭제 기준. 기기 시각으로 지우면 시계가 틀어진 기기의 행이 영원히 남거나 즉시 사라진다.
CREATE INDEX ix_subway_binding_event_received
    ON subway_binding_event (received_at);

COMMENT ON TABLE subway_binding_event IS
    '탑승 열차 판정의 관측·판단 원본. 후보 목록의 원본이기도 하다';
COMMENT ON COLUMN subway_binding_event.occurred_at IS
    '기기·원천 시각. 믿지 않는다 - 순서와 보관의 기준은 received_at 이다';
COMMENT ON COLUMN subway_binding_event.detail IS
    '후보 목록과 판단 근거. 조정할 때마다 모양이 바뀌므로 칼럼으로 박지 않는다';
