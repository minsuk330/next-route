-- 진행 링 원격 갱신(Live Activity push)의 발송 대기열.
--
-- 왜 journey_notification(V40)을 재사용하지 않나. 전달 보장의 모양이 반대다.
--   journey_notification = at-least-once. "환승 3분 전"은 한 번 일어난 사건이라 늦더라도 가야 한다
--   이 표                = latest-wins.   링 갱신은 최신 하나만 의미가 있고, 늦게 도착한 옛 상태는
--                          새 화면을 덮어 사용자를 되돌린다
-- 상태 6개·2겹 멱등 키·재시도 사다리를 그대로 가져오면 그 전부가 "낡은 것도 반드시 보낸다"를
-- 향해 있어 정확히 반대로 동작한다.
--
-- 그렇다고 재시도를 통째로 없애지도 않는다. commit 은 됐는데 push 가 유실되면 잠금화면이 멈춘
-- 채로 남는다. 규칙은 "최신인 동안만 재시도한다"이다.

CREATE TABLE subway_ring_push_outbox (
    id              bigint generated by default as identity primary key,
    created_at      timestamp(6) not null,
    updated_at      timestamp(6) not null,
    -- 이 표의 행은 지우지 않는다. 소프트 삭제도 하지 않는다 - 지우는 순간 순번이 되감겨,
    -- 늦게 도착한 옛 push 를 가려낼 근거가 사라진다. 칼럼이 있는 것은 BaseEntity 가 주기
    -- 때문이고 여기서는 쓰지 않는다(V40 과 같은 이유).
    deleted_at      timestamp(6),

    journey_id      bigint       not null references journey_session(id),
    route_revision  integer      not null
        constraint subway_ring_outbox_revision_check check (route_revision >= 1),
    leg_index       integer      not null
        constraint subway_ring_outbox_leg_index_check check (leg_index >= 0),

    -- 이 payload 가 어느 고정 세대를 보고 만들어졌나.
    --
    -- route_revision 만으로는 부족하다. 재탐색 계승(SubwayLegBinding.inheritTo)은 새 행을 만들며
    -- version 을 0 으로 되돌리므로, 같은 개정본 안에서 일어난 리셋을 개정본 비교로는 못 잡는다.
    binding_version integer      not null
        constraint subway_ring_outbox_binding_version_check check (binding_version >= 0),

    -- 순서 키. 역순 배달이 새 상태를 옛 상태로 덮으면 안 된다.
    --
    -- Activity(=여정) 전체에서 단조 증가한다. ring 키별로 다시 시작하면 개정본이 오르거나 leg 이
    -- 바뀔 때 값이 되감겨, 늦게 도착한 옛 push 가 새 화면을 덮는다.
    sequence        bigint       not null
        constraint subway_ring_outbox_sequence_check check (sequence >= 1),

    -- APNs 가 순서를 가리는 값(aps.timestamp). 단위는 epoch **초**다 - props 안의 시각들은
    -- 밀리초라 여기서 1000배 오차가 조용히 난다.
    --
    -- sequence 와 같은 원천에서 파생한다. 이미 SENDING 인 것을 취소할 수는 없으므로, 역전을
    -- 실제로 막는 최후 방어선이 이 값의 단조성이다.
    aps_timestamp   bigint       not null
        constraint subway_ring_outbox_aps_timestamp_check check (aps_timestamp > 0),

    -- 같은 화면이면 다시 보내지 않는다. 링 갱신은 5초마다 도는데 대부분의 tick 은 화면을
    -- 바꾸지 않는다.
    signature       varchar(64)  not null,

    -- 중요 이벤트만 최신인 동안 재시도한다. 다음 역 변경·하차 국면 전환·신선도 반전·실제
    -- 도착·종료가 여기 해당한다.
    critical        boolean      not null default false,

    -- 왜 이 행이 생겼나. 지표 tag 로 쓴다.
    reason          varchar(30)  not null,

    event           varchar(10)  not null
        constraint subway_ring_outbox_event_check check (event in ('update', 'end')),

    -- {name, props} 두 겹 그대로. props 는 JSON **문자열**이다 - Expo Widgets 의 실제
    -- ContentState 가 봉투 모양이라, 한 겹으로 보내면 앱 디코딩이 실패해 갱신이 조용히 무시된다.
    payload         jsonb        not null,

    status          varchar(20)  not null
        constraint subway_ring_outbox_status_check
            check (status in ('PENDING', 'SENDING', 'SENT', 'SKIPPED', 'FAILED')),

    attempt_count   integer      not null default 0
        constraint subway_ring_outbox_attempt_count_check check (attempt_count >= 0),

    -- 이 시각을 넘기면 보내지 않는다. 늦게 뜬 진행률은 거짓말이다.
    expires_at      timestamptz  not null,
    sending_at      timestamptz,
    sent_at         timestamptz,
    last_failure_reason varchar(200)
);

-- 여정·개정본·단계마다 살아 있는 PENDING 은 하나. 새 것이 오면 옛 것을 SKIPPED 로 밀고 갈아탄다.
--
-- 이것만으로는 부족하다는 것을 알아 두어야 한다. 워커가 행을 PENDING → SENDING 으로 옮기는
-- 순간 그 행은 이 술어에서 빠지므로, 그때 갱신 tick 이 새 PENDING 을 넣을 수 있다. 그 창은
-- 발송 직전 최신성 재확인이 막는다(SubwayRingPushRelayService).
CREATE UNIQUE INDEX uq_subway_ring_outbox_open
    ON subway_ring_push_outbox (journey_id, route_revision, leg_index)
    WHERE status = 'PENDING';

-- 순서 키의 유일성. 동시 삽입이 같은 번호를 두 번 쓰면 그 둘의 선후를 영영 못 가린다.
CREATE UNIQUE INDEX uq_subway_ring_outbox_sequence
    ON subway_ring_push_outbox (journey_id, sequence);

-- relay 가 집어 갈 행.
CREATE INDEX idx_subway_ring_outbox_due
    ON subway_ring_push_outbox (created_at)
    WHERE status = 'PENDING';

-- 발송 직전 최신성 재확인과 signature 대조가 타는 길.
CREATE INDEX idx_subway_ring_outbox_latest
    ON subway_ring_push_outbox (journey_id, route_revision, leg_index, sequence DESC);

-- 고착 SENDING 회수. 워커가 죽으면 그 행은 아무도 건드리지 않는다.
CREATE INDEX idx_subway_ring_outbox_sending
    ON subway_ring_push_outbox (sending_at)
    WHERE status = 'SENDING';
