-- Live Activity 원격 갱신의 수신 주소.
--
-- 왜 user_push_token(V39)에 합치지 않나. 수명이 다르다.
--   FCM registration token  = 기기·앱 설치 단위. 앱을 지우기 전까지 산다
--   ActivityKit push token  = Activity 단위. 잠금화면 위젯 하나가 끝나면 폐기되고, 사는 동안에도
--                             회전한다
-- 한 표에 넣으면 "회전했다"와 "기기가 바뀌었다"를 구분할 수 없고, Activity 를 끝낼 때 기기
-- 주소까지 함께 지우게 된다.
--
-- 발송에는 두 토큰이 다 필요하다. FCM 이 Message.token 으로 기기를 찾고
-- apns.live_activity_token 으로 그 기기 안의 어느 Activity 인지를 찾는다. 그래서 이 표가
-- user_push_token 을 참조한다.
--
-- 토큰은 journey 단위다. leg_index·binding_version 축을 여기 더하지 않는다 - 재탐색으로
-- 개정본이 올라도 잠금화면의 Activity 는 그대로이므로, 축을 더하면 계승마다 앱이 토큰을 다시
-- 등록해야 하고 그 사이 push 가 통째로 끊긴다. 낡은 payload 를 막는 일은 outbox(V47)가 한다.
--
-- push_type 칼럼을 두지 않는다. 이 표는 update/end 전용이다. push-to-start(iOS 17.2+)는 범위
-- 밖이고, 미리 넣으면 쓰지 않는 값이 계약처럼 굳는다.
--
-- 토큰은 개인식별에 준해 다룬다. 응답·로그·telemetry·metric tag 어디에도 싣지 않는다(V39 관례).

CREATE TABLE subway_live_activity_token (
    id             bigint generated by default as identity primary key,
    created_at     timestamp(6) not null,
    updated_at     timestamp(6) not null,
    deleted_at     timestamp(6),

    user_id        bigint       not null references users(id),
    journey_id     bigint       not null references journey_session(id),

    activity_token varchar(512) not null
        constraint subway_la_token_blank_check
            check (length(btrim(activity_token)) > 0),

    -- 이 Activity 를 들고 있는 기기.
    push_token_id  bigint       not null references user_push_token(id),

    -- iOS 개발 빌드는 APNs sandbox 를 받는다. V39 와 같은 이유로 구분해 둔다.
    environment    varchar(20)  not null default 'PRODUCTION'
        constraint subway_la_token_environment_check
            check (environment in ('PRODUCTION', 'DEVELOPMENT')),

    -- deleted_at 과 다른 사건이다(V39 규칙 계승).
    --   deleted_at    = 앱이 Activity 를 끝내며 스스로 해제했다
    --   enabled=false = provider 가 UNREGISTERED 라고 답해 우리가 껐다
    enabled        boolean      not null default true,
    last_seen_at   timestamptz  not null
);

-- 살아 있는 토큰 하나 = 행 하나. 재등록 upsert 의 ON CONFLICT 중재자이기도 하므로 술어가
-- upsert 문의 추론 절과 글자 그대로 같아야 한다.
--
-- 통 unique 를 걸지 않는 이유는 V39 와 같다 - 해제한 행이 표에 남으므로, 통 unique 면 같은
-- 토큰을 다시 받았을 때 영영 재등록하지 못한다.
CREATE UNIQUE INDEX uq_subway_la_token
    ON subway_live_activity_token (activity_token)
    WHERE deleted_at IS NULL;

-- 발송 대상 조회. 그 여정의 살아 있는 토큰 전부.
CREATE INDEX idx_subway_la_token_journey
    ON subway_live_activity_token (journey_id)
    WHERE enabled = true AND deleted_at IS NULL;
