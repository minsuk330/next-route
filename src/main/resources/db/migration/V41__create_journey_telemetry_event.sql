-- 앱이 보내는 이용행태 계측 원본. "알림을 눌렀다·화면에 들어왔다·행동했다"를 한 줄씩 쌓는다.
--
-- 왜 원본을 저장하나. alert-to-action(O15)은 두 사건의 시각 차이라 카운터만으로는 상관을 못 낸다.
-- 숫자만 남기면 "몇 번 눌렸나"는 알아도 "누르고 얼마 뒤에 움직였나"를 영영 못 구한다.
--
-- 이 표는 best-effort 신호다(SC-3). 여기 쓰기가 실패해도 여정 상태·발송·폴링은 흔들리지 않는다.

CREATE TABLE journey_telemetry_event (
    id                bigint generated by default as identity primary key,
    created_at        timestamp(6) not null,
    updated_at        timestamp(6) not null,
    deleted_at        timestamp(6),

    -- 앱이 만든 멱등 키. 지하철에서 응답을 못 받은 앱이 같은 batch 를 다시 보내므로,
    -- 이 값이 같으면 두 번째는 조용히 버린다(ON CONFLICT DO NOTHING).
    telemetry_id      varchar(64)  not null,

    -- 사용자는 토큰에서만 읽는다. 본문 값을 믿으면 남의 여정에 기록을 심을 수 있다.
    user_id           bigint       not null references users(id),
    -- 경로 자원이라 not null 이다(POST /api/journeys/{journeyId}/telemetry/batch).
    -- 여정 밖 이벤트(앱 진입 등)는 이번 범위 밖이다.
    journey_id        bigint       not null references journey_session(id),
    route_revision    integer,

    -- 값 목록을 서버 enum 으로 닫지 않는다. 앱이 먼저 배포되는 것이 정상 순서라, 모르는 값을
    -- 거부하면 새 이벤트를 붙이는 동안 batch 가 통째로 버려진다.
    event_type        varchar(40)  not null,

    -- 기기 시각. 시계가 틀어진 기기가 섞이므로 순서의 근거로도, 보관 삭제의 기준으로도 쓰지 않는다.
    occurred_at       timestamptz  not null,
    -- 서버 시각. 지연 계산과 보관 삭제의 기준이 이 값이다.
    received_at       timestamptz  not null,

    -- 어떤 알림에 대한 반응인가. FK 를 걸지 않는다 - 알림 행의 보관 정책이 이 표의 쓰기를
    -- 막으면 안 된다. 대신 아래 두 값을 수집 시점에 스냅샷해, 알림 행이 사라져도 상관이 남는다.
    alert_id          bigint,
    alert_checkpoint  varchar(40),
    alert_sent_at     timestamptz,

    -- 이벤트마다 실리는 값이 다르다. 전부 컬럼으로 박으면 앱이 이벤트를 하나 늘릴 때마다
    -- 서버 마이그레이션이 모바일 배포와 묶인다. 허용 키 목록의 스칼라만 저장한다(좌표 금지).
    detail            jsonb,

    -- 유일성을 전역으로 두지 않는다. 기기를 물려받아 계정이 바뀌면 앞선 사용자의 키가 새 사용자의
    -- 이벤트를 조용히 삼킨다. 앱이 전역 UUID 를 쓴다는 보장에 기대지 않는다.
    constraint uk_journey_telemetry_event_user_key unique (user_id, telemetry_id)
);

CREATE INDEX ix_journey_telemetry_event_journey
    ON journey_telemetry_event (journey_id, occurred_at);
CREATE INDEX ix_journey_telemetry_event_type_time
    ON journey_telemetry_event (event_type, occurred_at);
-- 보관 삭제(30일)가 이 컬럼으로 돈다. 기기 시각으로 지우면 시계를 미래로 돌린 기기의 데이터가
-- 영원히 남고, 과거로 돌린 기기의 데이터는 받자마자 지워진다.
CREATE INDEX ix_journey_telemetry_event_received
    ON journey_telemetry_event (received_at);

COMMENT ON TABLE journey_telemetry_event IS
    '앱 이용행태 계측 원본. best-effort 이며 여정 상태 전이의 근거로 쓰지 않는다';
COMMENT ON COLUMN journey_telemetry_event.occurred_at IS
    '기기 시각. 믿지 않는다 - 순서·보관의 기준은 received_at 이다';
COMMENT ON COLUMN journey_telemetry_event.alert_checkpoint IS
    '수집 시점에 서버가 알림 행에서 복사한 값. 알림이 지워져도 상관을 남긴다';
