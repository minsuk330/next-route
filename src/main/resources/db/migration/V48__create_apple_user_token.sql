-- 애플 로그인 사용자의 refresh_token 보관.
--
-- 왜 auth_identity(V33)에 합치지 않나. 토큰은 애플 로그인에만 있는 값이고 신원과 수명·민감도가
-- 다르다. 공통 신원 표에 넣으면 카카오 신원 행에도 빈 토큰 칸이 생기고, 토큰이 유출되면 신원까지
-- 함께 노출 범위에 든다. toss_user_token(V16)과 같은 이유로 별도 표를 둔다.
--
-- refresh_token_enc 는 SecretCipher(AES-256-GCM)로 암호화한 Base64 문자열이다. 평문을 넣지 않는다 -
-- 이 값은 애플에 "이 사용자 연결을 끊어라(revoke)"를 대신 낼 수 있는 권한이라, DB 유출 시 평문이면
-- 탈퇴 대행 권한을 그대로 넘기는 셈이다.

CREATE TABLE apple_user_token (
    id                bigint generated by default as identity primary key,
    created_at        timestamp(6) not null,
    updated_at        timestamp(6) not null,
    deleted_at        timestamp(6),

    user_id           bigint        not null references users(id),

    refresh_token_enc varchar(1024) not null
        constraint apple_user_token_enc_blank_check
            check (length(btrim(refresh_token_enc)) > 0),

    -- 애플 sub(providerSubject). 대조·조사용이며 신원 판단에는 쓰지 않는다.
    apple_sub         varchar(255),

    -- 사용자당 한 행. 재로그인마다 최신 토큰으로 갈아끼운다(upsert 중재자).
    constraint uq_apple_user_token_user unique (user_id)
);
