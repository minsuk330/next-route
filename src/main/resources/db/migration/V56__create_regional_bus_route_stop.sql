-- #267 경기·TAGO 노선별 정류장 순서(실시간 API 순번 그대로).
--
-- 두 가지 용도를 한 표가 진다.
--   1) TAGO 도시코드: 노선 → city_code. 접두사 하나가 여러 시군에 걸쳐(TSB 49곳, ADB·YDB 등)
--      접두사 단위 표로는 맞출 수 없다. 2026-10-06 실측: 138개 도시 21,393노선, 도시 간 중복 0.
--   2) #264 경기·지방 재탐색: GTFS 정류장 id → 실시간 순번. 실시간 순번에는 승객이 못 타는
--      경유 가상점이 끼어 있어 GTFS 순서로 셀 수 없다.
--
-- 노선 단위로 통째 교체한다(삭제 + 삽입을 한 트랜잭션에서). 엔티티는 두지 않는다.
CREATE TABLE regional_bus_route_stop (
    id         bigint generated by default as identity primary key,
    provider   varchar(8)       not null,
    route_id   varchar(32)      not null,
    route_no   varchar(64),
    city_code  varchar(8),
    stop_id    varchar(32)      not null,
    stop_name  varchar(100),
    seq        int              not null,
    turn       boolean,
    up_down    smallint,
    waypoint   boolean,
    lat        double precision,
    lon        double precision,
    loaded_at  timestamptz      not null,
    CONSTRAINT regional_bus_route_stop_provider_check CHECK (provider in ('GG', 'TAGO')),
    CONSTRAINT uq_regional_bus_route_stop UNIQUE (provider, route_id, seq)
);

CREATE INDEX idx_regional_bus_route_stop_stop ON regional_bus_route_stop (provider, stop_id);

COMMENT ON COLUMN regional_bus_route_stop.route_id IS
    '실시간 API 원본 노선 id. 경기 9자리(233000031), TAGO 접두사 포함(DJB30300151)';
COMMENT ON COLUMN regional_bus_route_stop.city_code IS
    'TAGO 도시코드. 경기 노선도 TAGO 노선 목록에서 온 값을 둔다';
COMMENT ON COLUMN regional_bus_route_stop.seq IS
    '실시간 API 순번(경기 stationSeq, TAGO nodeord). 경유 가상점 포함';
COMMENT ON COLUMN regional_bus_route_stop.waypoint IS
    '승객이 못 타는 경유 가상점. 경기는 이름의 (경유) 로 판별, TAGO 는 판별 전이라 null';
COMMENT ON COLUMN regional_bus_route_stop.loaded_at IS
    '이 노선을 마지막으로 적재한 시각. 적재가 끝까지 돈 실행보다 오래된 노선은 폐선으로 지운다';
