-- 지방 지하철(부산1~4, 대구1~3, 대전1, 광주1) 공식 시간표 기반 도착(docs/plan/subway-regional-timetable).
--
-- 서울 subway_station 과 분리한다. 서울 노선 id(1001~1099)는 서울 API 이름("N호선")으로 해석되고
-- OtpSeoulIdentityResolver 가 "부산1호선" 을 1001 로 잡는다. 지방 노선 코드는 문자열(BS1, DG2 ...).
--
-- 역은 커밋된 시드(resources/subway/regional-stations.json)를 worker 가 upsert 하고,
-- 출발 시각은 역 단위로 통째 교체한다(삭제 + 삽입을 한 트랜잭션에서). 엔티티는 두지 않는다.
CREATE TABLE regional_subway_station (
    id                    bigint generated by default as identity primary key,
    station_key           varchar(16)           not null,
    line_code             varchar(8)            not null,
    line_name             varchar(32)           not null,
    station_name          varchar(64)           not null,
    seq                   int                   not null,
    tago_station_id       varchar(16),
    provider_station_code varchar(16),
    gtfs_stop_id          varchar(64),
    latitude              double precision      not null,
    longitude             double precision      not null,
    geom                  geography(Point,4326) not null,
    loaded_at             timestamptz           not null,
    CONSTRAINT uq_regional_subway_station_key UNIQUE (station_key),
    CONSTRAINT uq_regional_subway_station_seq UNIQUE (line_code, seq),
    CONSTRAINT regional_subway_station_line_check CHECK (line_code in
        ('BS1', 'BS2', 'BS3', 'BS4', 'DG1', 'DG2', 'DG3', 'DJ1', 'GJ1'))
);

CREATE INDEX idx_regional_subway_station_geom ON regional_subway_station USING gist (geom);
CREATE INDEX idx_regional_subway_station_gtfs ON regional_subway_station (gtfs_stop_id);

COMMENT ON COLUMN regional_subway_station.station_key IS
    '{line_code}-{운영사 역코드}. 예 BS1-119(서면), DG2-230(반월당), BS1-95(다대포해수욕장)';
COMMENT ON COLUMN regional_subway_station.seq IS
    '노선 위 일직선 순서(0..n-1). 방향 판정은 이 순서로 한다(상행/하행 라벨 짝은 노선마다 달라 쓰지 않는다)';
COMMENT ON COLUMN regional_subway_station.provider_station_code IS
    '운영사 역코드. 부산 scode, 대구 STT_CD, 대전·광주 역번호';
COMMENT ON COLUMN regional_subway_station.gtfs_stop_id IS
    'OTP(KTDB GTFS) 정류장 id. 검색 결과와 여정 leg 를 이 역에 잇는다';

CREATE TABLE regional_subway_departure (
    id            bigint generated by default as identity primary key,
    station_key   varchar(16) not null,
    day_type      varchar(2)  not null,
    dep_seconds   int         not null,
    terminal_name varchar(64) not null,
    terminal_seq  int         not null,
    source        varchar(16) not null,
    source_date   date,
    loaded_at     timestamptz not null,
    CONSTRAINT regional_subway_departure_day_check CHECK (day_type in ('WD', 'SA', 'HO', 'MH')),
    CONSTRAINT regional_subway_departure_source_check CHECK (source in ('TAGO', 'BUSAN_API', 'DAEGU_API', 'GWANGJU_CSV')),
    CONSTRAINT uq_regional_subway_departure UNIQUE (station_key, day_type, dep_seconds, terminal_seq)
);

CREATE INDEX idx_regional_subway_departure_lookup ON regional_subway_departure (station_key, day_type, dep_seconds);

COMMENT ON COLUMN regional_subway_departure.day_type IS
    'WD 평일, SA 토요일, HO 공휴일(일요일 포함), MH 명절(광주만). 행이 없는 요일의 대체는 RegionalDayTypePolicy 가 조회 때 정한다';
COMMENT ON COLUMN regional_subway_departure.dep_seconds IS
    '서비스일 0시 기준 초. 04:00 전 시각과 24:xx 표기는 86400 이상(00:16 = 87360)';
COMMENT ON COLUMN regional_subway_departure.terminal_seq IS
    '그 열차 종착역의 seq. 타는 역과 내릴 역 사이 방향, 내릴 역 전에 끝나는 열차 제외에 쓴다';
COMMENT ON COLUMN regional_subway_departure.source IS
    'TAGO(대전), BUSAN_API(부산교통공사), DAEGU_API(대구교통공사 API 를 브라우저로 내보낸 파일), GWANGJU_CSV(광주교통공사 공식 파일)';
