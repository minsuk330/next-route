-- GTFS(OTP) 식별 → 서울 실시간/ML 공급자 식별 매핑 (national-otp P2-D).
--
-- 왜 필요한가. OTP leg 는 GTFS stop/route id(예: 1:BS_TAGO_...)를 들고 있는데, 서울 실시간 API 는
-- 별도 ID(ARS/localStationID/route_id)를 쓴다. 번호·이름만 같은 자동 매칭은 다른 지역 동명 노선을
-- 붙일 수 있어 금지한다 - 이 표는 지역/기관/승하차/순서/방향이 검증된 대응만 담는다.
--
-- 미매핑이거나 verification_status='REVIEW' 면 실시간을 붙이지 않고 STATIC_SCHEDULE 로 둔다.
-- 잘못된 매핑이 실시간을 오염시키는 것보다 정적 표시가 낫다.
--
-- data_version 별 immutable. 활성 snapshot 이 참조하는 버전은 덮어쓰지 않고 새 버전으로만 교체한다.
-- 같은 정류장 재방문은 occurrence_index 로 구분한다(source_stop_sequence 와 다른 개념).

CREATE TABLE transit_identity_mapping (
    id                   bigint generated by default as identity primary key,
    created_at           timestamp(6) not null,
    updated_at           timestamp(6) not null,
    deleted_at           timestamp(6),

    -- 매핑 아티팩트 버전. 재빌드마다 올린다.
    data_version         varchar(64)  not null,

    -- canonical(GTFS/OTP) 쪽
    feed_id              varchar(64)  not null,
    agency_id            varchar(128) not null,
    source_route_id      varchar(255) not null,
    trip_pattern         varchar(255),
    source_stop_id       varchar(255) not null,
    source_stop_sequence integer,
    occurrence_index     integer      not null default 0,

    -- provider(서울) 쪽
    provider             varchar(32)  not null,
    provider_route_id    varchar(255) not null,
    provider_stop_id     varchar(255) not null,
    provider_ars_id      varchar(64),
    direction            varchar(32),
    provider_seq         integer,

    -- 검증
    verification_status  varchar(16)  not null,
    evidence             text,

    -- (버전, canonical 키, provider) 복합 유일. 같은 canonical 을 여러 provider 로 매핑 가능하되
    -- 한 provider 로는 한 번만.
    --
    -- NULLS NOT DISTINCT (PG15+): trip_pattern 은 OTP 유입에서 null 이 일반적인데, 기본 UNIQUE 는
    -- NULL 을 서로 다르게 취급해 null 행끼리 중복이 통과한다 - 그러면 같은 정류장을 다른 provider_stop_id
    -- 로 두 번 매핑해도 DB 가 못 막아 잘못된 실시간 ID 가 VERIFIED 로 붙는다. NULL 을 같은 값으로 봐야
    -- 이 표의 유일성이 실제로 성립한다.
    constraint uq_transit_identity_mapping unique nulls not distinct
        (data_version, feed_id, agency_id, source_route_id, trip_pattern,
         source_stop_id, occurrence_index, provider)
);

-- 조회 index: (버전 + canonical 키)로 lookup 한다.
CREATE INDEX idx_transit_identity_mapping_lookup
    ON transit_identity_mapping
    (data_version, feed_id, agency_id, source_route_id, source_stop_id, occurrence_index);
