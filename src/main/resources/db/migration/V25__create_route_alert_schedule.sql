-- 반복(요일)/일회성 목표 도착 알림 구독 규칙. schedule 은 좌표·시각·요일셋을 소유하고,
-- spawner 가 in-flight occurrence(route_arrival_alert)를 최대 1개 유지한다.
-- occurrence 상태머신(V23/V24)은 무변경 — 여기선 schedule 테이블 + alert.schedule_id 연결만 추가한다.

CREATE TABLE route_alert_schedule (
    id                             bigint generated by default as identity primary key,
    created_at                     timestamp(6),
    updated_at                     timestamp(6),
    deleted_at                     timestamp(6),
    user_id                        bigint            not null references users,
    -- 좌표: 끝자리 단일 대문자(startX/endX) → CamelCaseToUnderscores 규칙상 underscore 없음.
    startx                         double precision  not null,
    starty                         double precision  not null,
    start_name                     varchar(255),
    endx                           double precision  not null,
    endy                           double precision  not null,
    end_name                       varchar(255),
    arrival_time                   time              not null,          -- HH:mm
    weekdays_mask                  integer           not null,          -- bit0=월…bit6=일, 0=일회성
    repeat                         boolean           not null,          -- true=반복, false=일회성
    user_lead_minutes              integer           not null,          -- {0,5,10,15}
    buffer_minutes                 integer           not null,
    last_spawned_target_arrival_at timestamp(6),                        -- 마지막 materialize 된 occurrence 목표시각
    -- retry metadata (시스템오류만. too-late/운행불가=roll-forward 는 미기록)
    last_materialization_failed_at timestamp(6),
    last_materialization_error     varchar(500),
    materialization_retry_count    integer           not null default 0,
    next_materialization_retry_at  timestamp(6),                        -- 백오프 게이트
    status                         varchar(255)      not null
        constraint route_alert_schedule_status_check
            check (status in ('ACTIVE', 'COMPLETED', 'CANCELED')),
    version                        bigint            not null default 0 -- @Version 낙관락(spawner 동시성)
);

-- 사용자별 구독 조회.
CREATE INDEX idx_route_alert_schedule_user
    ON route_alert_schedule (user_id) WHERE deleted_at IS NULL;
-- spawner 스캔(ACTIVE).
CREATE INDEX idx_route_alert_schedule_status
    ON route_alert_schedule (status) WHERE deleted_at IS NULL;

-- occurrence → schedule 출처(null=구모델/직접). occurrence 상태머신은 무변경.
ALTER TABLE route_arrival_alert
    ADD COLUMN schedule_id bigint REFERENCES route_alert_schedule;

-- in-flight occurrence 조회(schedule_id + status).
CREATE INDEX idx_route_alert_inflight
    ON route_arrival_alert (schedule_id, status) WHERE deleted_at IS NULL;
-- occurrence 중복 생성 방지(즉시생성·spawner·재시도·다중 인스턴스). 구모델(schedule_id null) 제외.
CREATE UNIQUE INDEX uq_route_alert_schedule_target
    ON route_arrival_alert (schedule_id, target_arrival_at)
    WHERE schedule_id IS NOT NULL AND deleted_at IS NULL;
