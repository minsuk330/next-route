-- 남는다(V80) → 검색과 여정이 정확히 이어진다. 경로가 없거나 스냅샷 저장이 실패한 검색은 null.
-- 보관 90일(worker 가 매일 지운다). 탈퇴 시 물리 삭제.
CREATE TABLE route_search_event (
    id                bigint generated by default as identity primary key,
    search_session_id varchar(64),
    user_id           bigint      references users(id),
    searched_at       timestamptz not null,
    outcome           varchar(20),
    path_count        integer     not null,
    latency_ms        integer     not null
);

CREATE UNIQUE INDEX uq_route_search_event_session
    ON route_search_event (search_session_id) WHERE search_session_id IS NOT NULL;
CREATE INDEX idx_route_search_event_searched_at ON route_search_event (searched_at);
CREATE INDEX idx_route_search_event_user ON route_search_event (user_id) WHERE user_id IS NOT NULL;
