-- 지하철 단계 하나가 어느 열차에 묶였는지. journey_leg 과 1:1 이다.
--
-- 왜 journey_leg 컬럼이 아닌가.
--   ① journey_leg 은 재탐색마다 전 단계가 통째로 복제되는 표다. 지하철에만 쓰이는 칼럼 여덟 개를
--      얹으면 그 폭이 개정본 수만큼 증폭되고, 도보·버스 단계 행까지 함께 넓어진다
--   ② 그보다 큰 이유 — 복제가 기본이면 재탐색 때 열차번호가 딸려간다. 경로가 바뀌었는데 옛 열차가
--      살아남으면 사용자는 엉뚱한 역에서 내린다. 표를 나누면 새 개정본의 leg 은 행이 없어
--      "고정 없음"이 기본이 되고, 계승은 명시적으로 만들 때만 일어난다. 빠뜨렸을 때 안전한 쪽이다
--   ③ status 가 부분 인덱스 조건이라, 상태가 바뀔 때마다 journey_leg 의 HOT update 가 깨진다.
--      그 표는 진행도 보고로 이미 자주 갱신된다
--
-- 대가는 조회 join 한 번이다. 스냅샷 조립이 이미 leg 와 노선 후보를 묶어 읽으므로 형태가 같다.
--
-- 이 표는 소프트 삭제하지 않는다. deleted_at 은 표 관례상 두지만 채우지 않는다 — 지우고 새 행을
-- 만들면 version 과 reset_generation 이 0 으로 돌아가, 늦게 도착한 갱신이 되살아난다.
-- (journey_notification 이 같은 이유로 통 unique 와 "삭제 금지"를 명시하고 있다)

CREATE TABLE subway_leg_binding (
    id                  bigint generated by default as identity primary key,
    -- 감사 칼럼만 timestamp(6). 도메인 절대시각은 timestamptz 다(V35 와 같은 규칙).
    created_at          timestamp(6) not null,
    updated_at          timestamp(6) not null,
    deleted_at          timestamp(6),

    -- 고정은 '타고 가는' 단계가 소유한다. 대기 단계로 들어온 요청은 짝 RIDE 로 옮겨 적는다.
    -- 노선 후보(journey_leg_route_option)를 대기 단계가 소유하므로 축을 나눠 둔다.
    journey_leg_id      bigint       not null references journey_leg(id),

    -- 여정 단위 정리와 개정본 판별을 leg join 없이 하기 위한 비정규화.
    -- 이 표에 행을 넣는 경로는 evidence 수신 한 곳뿐이고, 거기서 leg 을 읽어 채운다.
    journey_id          bigint       not null references journey_session(id),
    route_revision      integer      not null
        constraint subway_leg_binding_revision_check check (route_revision >= 1),
    leg_index           integer      not null
        constraint subway_leg_binding_leg_index_check check (leg_index >= 0),

    -- PENDING      이동 시작은 받았지만 아직 열차를 못 골랐다
    -- PROVISIONAL  후보를 골랐지만 확정 전이다. 하차 안내를 내보내지 않는다
    -- CONFIRMED    다음 역 정차까지 맞아떨어졌다
    -- ABANDONED    시간이 지났거나 사용자가 타지 않았다고 알렸다
    --
    -- CORRECTED 를 여기 두지 않는다. 교정은 CONFIRMED 로 끝나고, 교정이 있었다는 사실은
    -- 감사 표(subway_binding_event)에만 남는다. 지속 상태에 두면 한 트랜잭션 안에서만 존재하는
    -- 유령 상태가 되어 DB 에서는 관측되지 않는다.
    status              varchar(20)  not null
        constraint subway_leg_binding_status_check
            check (status in ('PENDING', 'PROVISIONAL', 'CONFIRMED', 'ABANDONED')),

    -- 열차를 가리키는 값 전체. 열차번호 하나로는 부족하다 - 자정 전후로 번호가 재사용되고
    -- 노선마다 겹치는 번호도 있다. 운행일·노선·방향이 함께 있어야 한 열차를 가리킨다.
    train_no            varchar(32),
    train_service_date  date,
    train_line_id       varchar(16),
    train_direction     varchar(10),

    -- 센서가 이동 시작을 감지한 시각. 실제 승차 시각이 아니다 - boarded_at 이라 부르면
    -- 추정값이 사실을 참칭한다.
    boarded_detected_at timestamptz,

    source              varchar(30)
        constraint subway_leg_binding_source_check
            check (source is null or source in
                  ('MOTION_AUTOMOTIVE', 'MOTION_UNKNOWN', 'USER_MANUAL', 'INHERITED_ON_REROUTE')),
    confidence          varchar(10)
        constraint subway_leg_binding_confidence_check
            check (confidence is null or confidence in ('LOW', 'MEDIUM', 'HIGH')),

    -- 낙관적 잠금. 늦게 도착한 관측이나 재처리된 워커가 이미 교정된 결과를 되돌리지 못하게 한다.
    version             integer      not null default 0
        constraint subway_leg_binding_version_check check (version >= 0),

    -- 사용자 보정 세대. 사용자가 "다른 열차를 탔다"고 알리면 올라간다.
    -- 이 값이 없으면 판정기가 같은 관측을 다시 읽어 방금 거부한 열차를 그대로 다시 고른다.
    reset_generation    integer      not null default 0
        constraint subway_leg_binding_reset_gen_check check (reset_generation >= 0),

    -- 관측 순번을 종류별로 나눠 든다. 이동 시작과 정차는 각각 1 부터 세므로,
    -- 한 칸에 담으면 두 흐름이 서로를 덮는다.
    last_movement_seq   integer
        constraint subway_leg_binding_movement_seq_check
            check (last_movement_seq is null or last_movement_seq >= 0),
    last_episode_seq    integer
        constraint subway_leg_binding_episode_seq_check
            check (last_episode_seq is null or last_episode_seq >= 0),

    -- 열차를 가리키는 네 값은 함께 있거나 함께 없다. 일부만 채워지면 그 행은 어느 열차도
    -- 가리키지 못하면서 가리키는 척한다.
    constraint subway_leg_binding_train_identity_check
        check ((train_no is null and train_service_date is null
                and train_line_id is null and train_direction is null)
            or (train_no is not null and train_service_date is not null
                and train_line_id is not null and train_direction is not null)),

    -- 열차를 골랐다는 상태라면 그 열차가 누구인지 반드시 있어야 한다.
    constraint subway_leg_binding_bound_requires_train_check
        check (status not in ('PROVISIONAL', 'CONFIRMED') or train_no is not null),

    -- 이 표는 삭제하지 않으므로 통 unique 다. 부분 unique 로 두면 삭제 후 재삽입 경로가 열려
    -- version 이 초기화되는 길이 생긴다.
    constraint uk_subway_leg_binding_leg unique (journey_leg_id)
);

-- 판정기가 훑는 대상. 아직 끝나지 않은 것만 남아야 인덱스가 계속 자라지 않는다.
-- 조회가 여정과 개정본으로 좁히므로 그 순서로 세운다.
CREATE INDEX ix_subway_leg_binding_pending
    ON subway_leg_binding (journey_id, route_revision)
    WHERE status IN ('PENDING', 'PROVISIONAL');

COMMENT ON TABLE subway_leg_binding IS
    '지하철 단계가 고정한 열차. journey_leg 과 1:1 이며 재탐색 복제 대상이 아니다. 행을 지우지 않는다';
COMMENT ON COLUMN subway_leg_binding.boarded_detected_at IS
    '센서가 이동 시작을 감지한 시각. 실제 승차 시각이 아니다';
COMMENT ON COLUMN subway_leg_binding.reset_generation IS
    '사용자 보정 세대. 이전 세대의 후보는 재판정에 쓰지 않는다';
COMMENT ON COLUMN subway_leg_binding.version IS
    '낙관적 잠금. 늦게 온 갱신이 교정된 결과를 되돌리지 못하게 한다';
