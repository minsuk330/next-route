-- 여정 알림을 보낼 곳. 사용자 한 명이 여러 기기(=여러 token)를 가질 수 있다.
--
-- 기기 테이블을 두지 않는다(SC-1). 기기 식별자를 저장하지 않고 사용자와 token 만 묶는다.
-- 발송 대상은 "그 사용자의 살아 있는 enabled token 전부"다.
--
-- unique 는 (user_id, token) 이 아니라 token 하나다. 기기를 물려주거나 같은 폰에서 계정을
-- 바꿔 로그인하면 같은 token 이 다른 사용자로 다시 등록된다. 그때 앞선 소유자에게서 떼어 내지
-- 않으면 한 기기에 두 사람의 여정 알림이 간다. 복합 unique 로는 DB 가 그 사고를 못 막는다.
--
-- 유일성을 부분 인덱스로 거는 이유. 이 코드베이스는 소프트 삭제가 수동이라 해제한 token 의
-- 행이 표에 남는다. 통 unique 를 걸면 한 번 해제한 token 을 그 기기가 영영 다시 등록하지
-- 못한다 - FCM 은 재설치·재로그인 뒤에도 같은 token 을 그대로 내줄 수 있다.
--
-- enabled 와 deleted_at 은 다른 사건이다.
--   deleted_at    = 사용자·앱이 스스로 해제했다(로그아웃, DELETE /api/me/push-token)
--   enabled=false = provider 가 UNREGISTERED 라고 답해 우리가 껐다(Phase 5 PR3)
-- 껐다고 지우지 않는다. 그 수를 세야 하고(PR7 지표), 같은 token 이 다시 등록되면 되살려야 한다.
--
-- token 은 개인식별에 준해 다룬다. 로그·telemetry·metric tag 에 싣지 않는다(REQUIREMENTS 6장).

CREATE TABLE user_push_token (
    id           bigint generated by default as identity primary key,
    created_at   timestamp(6) not null,
    updated_at   timestamp(6) not null,
    deleted_at   timestamp(6),
    user_id      bigint       not null references users(id),
    platform     varchar(20)  not null
        constraint user_push_token_platform_check
            check (platform in ('ANDROID', 'IOS')),
    provider     varchar(20)  not null default 'FCM'
        constraint user_push_token_provider_check
            check (provider in ('FCM')),
    token        varchar(512) not null
        constraint user_push_token_token_blank_check
            check (length(btrim(token)) > 0),
    -- iOS 개발 빌드는 APNs sandbox token 을 받는다. 운영 설정으로 보내면 실패하므로 구분해 둔다.
    environment  varchar(20)  not null default 'PRODUCTION'
        constraint user_push_token_environment_check
            check (environment in ('PRODUCTION', 'DEVELOPMENT')),
    enabled      boolean      not null default true,
    last_seen_at timestamptz  not null
);

-- token 하나는 살아 있는 행 하나. 재등록 upsert 의 ON CONFLICT 중재자이기도 하므로
-- 술어(WHERE deleted_at IS NULL)가 upsert 문의 추론 절과 글자 그대로 같아야 한다.
CREATE UNIQUE INDEX uq_user_push_token_token
    ON user_push_token (token)
    WHERE deleted_at IS NULL;

-- 발송 대상 조회 경로(Phase 5 PR2·PR3). 사용자 한 명의 살아 있는 enabled token 전부.
CREATE INDEX idx_user_push_token_user_enabled
    ON user_push_token (user_id)
    WHERE enabled = true AND deleted_at IS NULL;
